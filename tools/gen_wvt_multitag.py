#!/usr/bin/env python3
"""Generate the multi-tag WRF-WVT pieces for up to MAX_TAGS moisture tags.

Tag 1 keeps the original WRF-WVTs names (qv_tr, TRMASK, TR_RAINNC, ...), so a
tracer_opt=4 run is unchanged.  Tags 2..MAX_TAGS get the same fields with a
_t<N> suffix (qv_tr_t2, TRMASK_T2, TR_RAINNC_T2, ...); a bare number would
collide (TRMASK3D + 2 = TRMASK3D2, the tag-1 sink mask).

    tracer_opt = 4          1 tag  (original WRF-WVTs)
    tracer_opt = 40 + N     N tags, N = 2..MAX_TAGS

Writes (paths relative to the WRF top directory):
    Registry/registry.wvt_multitag   tracer species, per-tag state, packages
    dyn_em/wvt_tags_set.h          pointer table body used by module_wvt_set.F
    share/wvt_max_tags.h           INTEGER, PARAMETER :: wvt_max_tags

Usage:  python3 tools/wvt_multitag/gen_wvt_multitag.py [MAX_TAGS]   (default 10)
then recompile (./clean; ./compile em_real).
"""
import os
import shlex
import sys

TOP = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MAX_TAGS = int(sys.argv[1]) if len(sys.argv) > 1 else 10
assert 2 <= MAX_TAGS <= 59, 'tracer_opt = 40+N must stay below 100'

# the six moisture tracer species of WRF-WVTs (Registry.EM, tag 1)
SPECIES = [('qv', 'water vapor'), ('qc', 'cloud water'), ('qr', 'rain water'),
           ('qi', 'ice'), ('qs', 'snow'), ('qg', 'graupel')]
SPECIES_FLAGS = 'irh06usdf=(bdy_interp:dt)'


def tagname(name, t):
    if t == 1:
        return name
    return '%s_%s%d' % (name, 'T' if name.isupper() else 't', t)


def read_moisttracer_state():
    """state lines of registry.moisttracers -> list of token lists"""
    rows = []
    with open(os.path.join(TOP, 'Registry', 'registry.moisttracers')) as f:
        for line in f:
            tok = shlex.split(line, comments=True)
            if len(tok) >= 10 and tok[0] == 'state':
                rows.append(tok)
    return rows


def registry(state_rows):
    out = ['# Generated by tools/wvt_multitag/gen_wvt_multitag.py -- do not edit.',
           '# Multi-tag WRF-WVTs: tags 2..%d (tag 1 = the original fields).' % MAX_TAGS,
           '#   tracer_opt = 4: 1 tag;  tracer_opt = 40+N: N tags (N = 2..%d)' % MAX_TAGS, '']
    for t in range(2, MAX_TAGS + 1):
        out.append('# ---- tag %d' % t)
        for s, desc in SPECIES:
            n = tagname(s + '_tr', t)
            out.append('state   real    %-10s ikjftb  tracer  1  -  %s  "%s"  "tag %d tracer for %s (mix. ratio)"  "Kg Kg-1"'
                       % (n, SPECIES_FLAGS, n, t, desc))
        for tok in state_rows:
            _, typ, name, dims, use, ntl, stag, io, dname, desc, units = (tok + [''])[:11]
            out.append('state    %s  %-20s %-4s %s %s %s %-6s "%s" "TAG %d %s" "%s"'
                       % (typ, tagname(name, t), dims, use, ntl, stag, io, tagname(dname, t), t, desc, units))
        out.append('')
    for n in range(2, MAX_TAGS + 1):
        tr = ','.join(tagname(s + '_tr', t) for t in range(1, n + 1) for s, _ in SPECIES)
        st = ','.join(tagname(tok[2], t).lower() for t in range(2, n + 1) for tok in state_rows)
        out.append('package   wvt_tags%d   tracer_opt==%d   -   tracer:%s;state:%s' % (n, 40 + n, tr, st))
    return '\n'.join(out) + '\n'


def setter_inc(state_rows):
    """Fortran SELECT CASE body: tag it -> species indices + grid field pointers"""
    out = ['! Generated by tools/wvt_multitag/gen_wvt_multitag.py -- do not edit.',
           '      SELECT CASE ( it )']
    for t in range(1, MAX_TAGS + 1):
        out.append('      CASE ( %d )' % t)
        for s, _ in SPECIES:
            out.append('        wvt(it)%%p_%s = P_%s' % (s, tagname(s + '_tr', t).upper()))
        for tok in state_rows:
            field = tok[2].lower()
            out.append('        wvt(it)%%%s => grid%%%s' % (field, tagname(field, t)))
    out.append('      END SELECT')
    return '\n'.join(out) + '\n'


def main():
    rows = read_moisttracer_state()
    with open(os.path.join(TOP, 'Registry', 'registry.wvt_multitag'), 'w') as f:
        f.write(registry(rows))
    with open(os.path.join(TOP, 'dyn_em', 'wvt_tags_set.h'), 'w') as f:
        f.write(setter_inc(rows))
    with open(os.path.join(TOP, 'share', 'wvt_max_tags.h'), 'w') as f:
        f.write('! Generated by tools/wvt_multitag/gen_wvt_multitag.py -- do not edit.\n'
                '      INTEGER, PARAMETER :: wvt_max_tags = %d\n' % MAX_TAGS)
    print('multi-tag WVT: %d tags, %d per-tag state fields -> registry.wvt_multitag, '
          'wvt_tags_set.h, wvt_max_tags.h' % (MAX_TAGS, len(rows)))


if __name__ == '__main__':
    main()
